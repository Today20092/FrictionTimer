import { expect, test } from "@playwright/test";
import { mockNativeBridge, savedApp } from "./native-bridge";

test("deleting an app requires confirmation and cancelling preserves its settings", async ({ page }) => {
  await mockNativeBridge(page);
  await page.goto("/app/saved-app");
  const deleteButton = page.getByRole("button", { name: "Delete", exact: true });
  await deleteButton.click();
  const confirmation = page.getByRole("alertdialog", { name: "Remove the pause for Reader?" });
  await expect(confirmation).toBeVisible();
  await expect(confirmation).toContainText("settings and messages");
  await expect(confirmation.getByRole("button", { name: "Keep app" })).toBeFocused();
  await page.screenshot({ path: test.info().outputPath("delete-confirmation.png") });
  await page.keyboard.press("Escape");
  await expect(confirmation).not.toBeVisible();
  await expect(deleteButton).toBeFocused();
  await deleteButton.click();
  await confirmation.getByRole("button", { name: "Keep app" }).click();
  await page.getByRole("button", { name: "Next" }).click();
  await expect(page.getByRole("group", { name: "Wait time" }).getByLabel("Seconds")).toHaveValue("20");
  await page.getByRole("button", { name: "Next" }).click();
  await expect(page.getByLabel("Message 1", { exact: true })).toHaveValue("Take a breath.");
});

test("failed deletion can be retried and removes only the confirmed app", async ({ page }) => {
  const native = await mockNativeBridge(page);
  native.apps.push({ ...savedApp, id: "other-app", appId: "com.example.notes", name: "Notes" });
  native.failures.add("delete_app");
  await page.goto("/app/saved-app");
  await page.getByRole("button", { name: "Delete", exact: true }).click();
  const confirmation = page.getByRole("alertdialog");
  await confirmation.getByRole("button", { name: "Delete pause" }).click();
  await expect(confirmation.getByRole("alert")).toContainText("Couldn't remove the pause");
  await expect(page).toHaveURL(/\/app\/saved-app$/);
  native.failures.delete("delete_app");
  native.delay = 500;
  await confirmation.getByRole("button", { name: "Delete pause" }).click();
  await expect(confirmation.getByRole("button", { name: "Deleting…" })).toBeDisabled();
  await expect(confirmation.getByRole("button", { name: "Keep app" })).toBeDisabled();
  await page.keyboard.press("Escape");
  await expect(confirmation).toBeVisible();
  await expect(page).toHaveURL("/");
  await expect(page.getByRole("link", { name: /Notes/ })).toBeVisible();
  await expect(page.getByRole("link", { name: /Reader/ })).not.toBeVisible();
});

test("saved-app list and detail failures have retry actions", async ({ page }) => {
  const native = await mockNativeBridge(page);
  native.failures.add("list_apps");
  await page.goto("/");
  const listFailure = page.getByRole("alert").filter({ hasText: "Couldn't load apps" });
  await expect(listFailure).toBeVisible();
  native.failures.delete("list_apps");
  await listFailure.getByRole("button", { name: "Retry" }).click();
  await expect(page.getByRole("link", { name: /Reader/ })).toBeVisible();
  native.failures.add("get_app");
  await page.getByRole("link", { name: /Reader/ }).click();
  const detailFailure = page.getByRole("alert").filter({ hasText: "Couldn't load app:" });
  await expect(detailFailure).toBeVisible();
  native.failures.delete("get_app");
  await detailFailure.getByRole("button", { name: "Retry" }).click();
  await page.getByRole("button", { name: "Next" }).click();
  await page.getByRole("button", { name: "Next" }).click();
  await page.getByLabel("Message 1", { exact: true }).fill("My unsaved reminder");
  native.failures.add("get_app");
  await page.evaluate(() => window.dispatchEvent(new Event("storage")));
  await expect(detailFailure).toBeVisible();
  native.failures.delete("get_app");
  await detailFailure.getByRole("button", { name: "Retry" }).click();
  await expect(detailFailure).not.toBeVisible();
  await expect(page.getByLabel("Message 1", { exact: true })).toHaveValue("My unsaved reminder");
});

test("settings-launch errors preserve checked permissions and can be retried", async ({ page }) => {
  const native = await mockNativeBridge(page);
  native.permissions = { overlay: true, accessibility: false, notifications: true };
  await page.goto("/");
  const overlay = page.getByRole("button", { name: "Display over other apps Enabled" });
  await expect(overlay).toBeVisible();
  native.failures.add("open_service_settings");
  await overlay.click();
  const failure = page.getByRole("alert").filter({ hasText: "Couldn't open Android settings" });
  await expect(failure).toBeVisible();
  await expect(overlay).toBeVisible();
  await expect(page.getByText("Unknown", { exact: true })).toHaveCount(0);
  native.failures.delete("open_service_settings");
  await overlay.click();
  await expect(failure).not.toBeVisible();
  native.permissions = { overlay: true, accessibility: true, notifications: true };
  await page.evaluate(() => document.dispatchEvent(new Event("visibilitychange")));
  await expect(page.getByRole("heading", { name: "Permissions", exact: true })).not.toBeVisible();
});

test("a failed navigation to another app never leaves the previous app editable", async ({ page }) => {
  const native = await mockNativeBridge(page);
  native.apps.push({ ...savedApp, id: "other-app", appId: "com.example.notes", name: "Notes" });
  await page.goto("/app/saved-app");
  await expect(page.getByRole("button", { name: "Delete", exact: true })).toBeVisible();
  native.failures.add("get_app");
  native.delay = 400;
  await page.evaluate(() => {
    history.pushState(null, "", "/app/other-app");
    window.dispatchEvent(new PopStateEvent("popstate"));
  });
  await expect(page.getByRole("button", { name: "Delete", exact: true })).not.toBeVisible();
  const failure = page.getByRole("alert").filter({ hasText: "Couldn't load app:" });
  await expect(failure).toBeVisible();
  await expect(page.getByRole("button", { name: "Delete", exact: true })).not.toBeVisible();
  native.failures.delete("get_app");
  await failure.getByRole("button", { name: "Retry" }).click();
  await page.getByRole("button", { name: "Delete", exact: true }).click();
  await expect(page.getByRole("alertdialog", { name: "Remove the pause for Notes?" })).toBeVisible();
});

